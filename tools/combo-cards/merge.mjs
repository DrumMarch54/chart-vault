#!/usr/bin/env node
// Writes knowledge/combo-cards.json (GENERATED, never hand-edited) from tools/combo-cards/batches/*.json, the cards
// Claude sessions write by the playbook (.brain/numerology/combinations.md, models in combination-cards-graded.md;
// how to write a batch: tools/combo-cards/BRIEF.md). A later batch replaces an earlier card with the same key.
// Every card is checked: two known spots that make a combination (server/neighbors.js PAIRS), numbers 1-99, the parts
// the owner approved and nothing else. A card that fails stops the merge with the reason.
import fs from 'node:fs';
import { POSITIONS } from '../../server/positions.js';
import { PAIRS, cardKey } from '../../server/neighbors.js';

const DIR = new URL('./batches/', import.meta.url);
const OUT = new URL('../../knowledge/combo-cards.json', import.meta.url);
const SPOTS = new Set(POSITIONS.filter((p) => !p.hidden).map((p) => `${p.chart}.${p.key}`));
const pairOk = (a, b) => PAIRS.some(([x, y]) => (x === a && y === b) || (x === b && y === a))
  || (a.split('.')[0] === b.split('.')[0] && ['first', 'middle', 'last'].includes(a.split('.')[1]) && ['first', 'middle', 'last'].includes(b.split('.')[1])); // names next to each other
const PARTS = ['a', 'b', 'phrases', 'position', 'share', 'course', 'reasoning', 'best', 'worst', 'made', 'graded', 'unreviewed', 'written'];
const str = (x) => typeof x === 'string' && x.trim().length > 0;

const cards = {};
const problems = [];
for (const f of fs.readdirSync(DIR).filter((x) => x.endsWith('.json')).sort()) {
  const batch = JSON.parse(fs.readFileSync(new URL(f, DIR), 'utf8'));
  for (const [i, c] of (batch.cards || []).entries()) {
    const where = `${f} card ${i + 1}`;
    const bad = (why) => problems.push(`${where}: ${why}`);
    if (!c.a || !c.b || !SPOTS.has(c.a.spot) || !SPOTS.has(c.b.spot)) { bad('a / b must name two known spots'); continue; }
    if (![c.a.sum, c.b.sum].every((n) => Number.isInteger(n) && n >= 1 && n <= 99)) { bad('numbers must be 1-99'); continue; }
    if (!pairOk(c.a.spot, c.b.spot)) { bad(`${c.a.spot} and ${c.b.spot} are not a combination (server/neighbors.js PAIRS)`); continue; }
    for (const k of Object.keys(c)) if (!PARTS.includes(k)) bad(`unknown part "${k}"`);
    if (!Array.isArray(c.phrases) || !c.phrases.length || !c.phrases.every(str)) bad('needs at least one phrase');
    if (!str(c.position)) bad('needs By Position');
    if (c.share && (!['What They Share', 'What Sets Them Apart'].includes(c.share.title) || !str(c.share.text))) bad('share needs the title What They Share or What Sets Them Apart, and text');
    if (c.course && !str(c.course.text)) bad('course needs text');
    if (c.reasoning && (!Array.isArray(c.reasoning) || !c.reasoning.every(str))) bad('reasoning is a list of points');
    for (const k of ['best', 'worst', 'made']) if (c[k] !== undefined && !str(c[k])) bad(`${k} is empty`);
    cards[cardKey(c.a.spot, c.a.sum, c.b.spot, c.b.sum)] = { ...c, batch: f.replace(/\.json$/, '') };
  }
}
if (problems.length) { console.error(problems.join('\n')); process.exit(1); }
fs.writeFileSync(OUT, JSON.stringify({ about: 'GENERATED by node tools/combo-cards/merge.mjs from tools/combo-cards/batches/*.json. Never edit by hand.', cards }, null, 1) + '\n');
console.log(`combo-cards: ${Object.keys(cards).length} cards written`);
