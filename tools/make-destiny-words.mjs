#!/usr/bin/env node
// Builds public/destiny-words.js: the Forecasting Book's words for each destiny period, one per planet number 1-9
// ("SUN 1 year Destiny period Balanced: … Unbalanced: … The Lessons: …", the chapter "Destiny Rhythms, planets and
// their significance"), plus the book's few lines on destiny years. Read from the knowledge store's text of the book
// (knowledge/raw/forecasting-book.md). The words are the book's, only joined where a page break split them.
// Run after a change here or in the source: node tools/make-destiny-words.mjs. Never hand-edit the output.
import fs from 'node:fs';
import path from 'node:path';
const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const src = fs.readFileSync(path.join(root, 'knowledge', 'raw', 'forecasting-book.md'), 'utf8');
const lines = src.split('\n');
const fail = (m) => { console.error(m); process.exit(1); };
const tidy = (s) => s.replace(/\s+/g, ' ').replace(/[”“]/g, '"').replace(/’/g, "'").trim();
const pageAt = (i) => { for (let j = i; j >= 0; j--) { const m = /^<!-- page (\d+) -->/.exec(lines[j]); if (m) return Number(m[1]); } return null; };

const start = lines.findIndex((l) => l.startsWith('Destiny Rhythms, planets and their significance'));
const end = lines.findIndex((l, i) => i > start && /WHAT ARE KARMIC CONTRACTS/.test(l));
if (start < 0 || end < 0) fail('the chapter "Destiny Rhythms, planets and their significance" was not found');

// The chapter's paragraphs, with the page each one sits on; page marks and the page headings dropped. A paragraph
// that does not open a new planet continues the one before (a page break split it): "infatua-" + "tion".
const PLANET = /\b(SUN|MOON|JUPITER|URANUS|MERCURY|VENUS|NEPTUNE|SATURN|MARS) (\d) year [Dd]estiny [Pp]eriod\b/g;
let text = '';
const pages = []; // [offset in text, page]
for (let i = start; i < end; i++) {
  const l = lines[i].trim();
  if (!l || /^<!--/.test(l) || /^#/.test(l)) continue;
  if (text.endsWith('-')) text = text.slice(0, -1); else if (text) text += ' ';
  pages.push([text.length, pageAt(i)]);
  text += l;
}
text = tidy(text);
const pageOf = (off) => { let p = null; for (const [o, pg] of pages) if (o <= off) p = pg; return p; };

const marks = [...text.matchAll(PLANET)];
const out = {};
marks.forEach((m, k) => {
  const n = Number(m[2]);
  const body = text.slice(m.index + m[0].length, k + 1 < marks.length ? marks[k + 1].index : text.length)
    .replace(/\s*(#+ )?DESTINY RHYTHM \d.*?PERIODS\s*$/, '').trim();
  const b = /^Balanced:\s*(.*?)\s*Unbalanced:\s*(.*?)\s*The Lessons?:\s*(.*)$/.exec(body);
  if (!b) fail(`period ${n}: Balanced / Unbalanced / The Lessons not found in "${body.slice(0, 120)}"`);
  const planet = m[1][0] + m[1].slice(1).toLowerCase();
  out[n] = { planet, balanced: b[1].replace(/[.,]$/, ''), unbalanced: b[2].replace(/[.,]$/, ''), lessons: b[3], page: pageOf(m.index), find: m[0] };
});
for (let n = 1; n <= 9; n++) if (!out[n]) fail(`no words for the ${n} year destiny period`);

// The book's lines on what a destiny year brings (a new destiny period starting).
const must = (q) => { if (!tidy(src).includes(q)) fail(`not found in the Forecasting Book: "${q}"`); return q; };
const general = {
  ruled: must('Each destiny period is ruled by a planet, and the things you experience during the period are rooted in the themes of that planet.'),
  years: must('Things like falling in love, getting married, divorced, pregnant or having a child are all things that typically happen when you enter a new destiny period - we call these "Destiny years".'),
  chapter: must('Every time you have a destiny year, it feels like a new life chapter opens up.'),
  page: 41,
};

const data = { periods: out, general };
const js = `// GENERATED by tools/make-destiny-words.mjs from the knowledge store's text of the Forecasting Book (the chapter
// "Destiny Rhythms, planets and their significance"). Never hand-edit: change the script and run it again.
// Used by the Year Rows popup: tap a destiny period for its planet's words.
(function (root) { root.DestinyWords = ${JSON.stringify(data, null, 1)}; })(typeof globalThis !== 'undefined' ? globalThis : this);
`;
fs.writeFileSync(path.join(root, 'public', 'destiny-words.js'), js);
console.log(`wrote public/destiny-words.js: ${Object.values(out).map((p) => `${p.planet} p${p.page}`).join(', ')}`);
