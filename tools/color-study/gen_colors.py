# table.json (from build_table.py) -> public/number-colors.js. Run from the work dir: python3 -I <this> <repo>/public/number-colors.js
import json, sys
from collections import defaultdict
table = {tuple(k): v for k, v in json.load(open('table.json'))}
out = defaultdict(dict)
for c, t in sorted({(c, t) for c, t, m in table}):
    a = table.get((c, t, False)); b = table.get((c, t, True))
    if a and b and a[0] != b[0]: out[c][t] = a[0]; out[c + '+'][t] = b[0]
    else: out[c][t] = (a or b)[0]
num = lambda t: int(t.split('/')[0]) if t[0].isdigit() else 999
lines = []
for c in sorted(out, key=lambda c: (c.rstrip('+'), c.endswith('+'))):
    lines.append(f"    '{c}': {{ {', '.join(f'{t!r}: {k!r}' for t, k in sorted(out[c].items(), key=lambda kv: num(kv[0])))} }},")
n_images = len(json.load(open('inputs.json'))); n_samples = len(json.load(open('samples.json')))
open(sys.argv[1], 'w').write(f"""/* Number colors of the paid Quick Numeroscope tool, read off {n_images} vault screenshots ({n_samples} numbers
   matched by position and value). Generated by tools/color-study (see .brain/numerology/number-colors.md);
   do not edit by hand. Key = position (see app.js numbers()); a trailing "+" = the name has exactly one
   middle name, which changes the center colors in the paid tool. Value = color class (app.css .n-<class>).
   Positions not listed fall back: day and essence dark, psyche blue (inner pillar dark), big numbers faded,
   everything else gray. */
(function (root) {{
  'use strict';
  const T = {{
{chr(10).join(lines)}
  }};
  const FIXED = {{ day: 'dark', 'c.day': 'dark', 'v.day': 'dark', letters: 'blue', big: 'faded', 'pi.pillar': 'dark' }};
  function lookup(slot, text, oneMiddle) {{
    if (slot in FIXED) return FIXED[slot];
    if (slot.startsWith('e.')) return 'dark';
    if (slot.startsWith('pi.') || slot.startsWith('po.')) return 'blue';
    const plus = oneMiddle && T[slot + '+'];
    return (plus && plus[text]) || (T[slot] && T[slot][text]) || (slot.endsWith('.big') ? 'faded' : 'gray');
  }}
  root.NumberColors = {{ table: T, lookup }};
}})(typeof globalThis !== 'undefined' ? globalThis : this);
""")
print('wrote', sys.argv[1], sum(len(v) for v in out.values()), 'entries')
