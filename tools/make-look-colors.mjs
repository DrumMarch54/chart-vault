#!/usr/bin/env node
// The dark looks (Glass on Color, Blueprint Night) for every screen (owner 2026-11-23: "Everything should be
// matching our theme"). Many tool screens were written for a white page with fixed colors (#fff cards, #303030
// text, #f3f4f7 boxes). This reads every rule in public/app.css above the marker, and for each fixed color writes the
// same rule again under html[data-style="glass"] / html[data-style="blueprint"] with the look's color instead:
// a white or pale gray ground -> the look's panel, dark text -> the look's text, mid gray -> muted, a pale tint
// (yellow note, green chip) -> the same hue, see-through, and dark colored text -> a lighter shade of it.
// Charts keep their white: anything that holds a drawn chart is listed in KEEP and never touched.
// GENERATED section: re-run `node tools/make-look-colors.mjs` after changing app.css; never edit the section by hand.
import fs from 'node:fs';

const FILE = new URL('../public/app.css', import.meta.url);
const START = '/* ===== GENERATED by tools/make-look-colors.mjs: dark looks for fixed colors. Do not edit by hand. ===== */';
const END = '/* ===== END GENERATED ===== */';
const DARK = ['glass', 'blueprint'];
// A drawn chart sits on white in every look (CLAUDE.md "Charts stay on white"): its boxes are left as they are.
const KEEP = /\.vimg|\.drawn|simthumb|\.cpane|\.fdrow svg|\.fdmini|nscope|\.n-|\bsvg\b|\.mini\b|\.cellsvg|\.ncell|\.scene|\.planet|\.viewer|\.vtop|\.nsfull|\.varrow|\.thumb|\.cell\b|\.dgrid|\.daychart|\.chartbox|\.vhl|::selection|html\.light\b(?!\s*\.)|^html\.day\b(?!\s*\.)|\.dayfull\b(?!\s*\.)|\.toast|#toast|\.btn-primary|\.act\.primary|\.solid|\.band\b|\.rate\b|\.hold/;

let css = fs.readFileSync(FILE, 'utf8');
const cut = css.indexOf(START);
if (cut >= 0) css = css.slice(0, cut).replace(/\s+$/, '\n');

const hexRgb = (h) => { h = h.slice(1); if (h.length === 3) h = [...h].map((c) => c + c).join(''); return [0, 2, 4].map((i) => parseInt(h.slice(i, i + 2), 16)); };
const lum = ([r, g, b]) => (0.2126 * r + 0.7152 * g + 0.0722 * b) / 255;
const sat = ([r, g, b]) => { const mx = Math.max(r, g, b), mn = Math.min(r, g, b); return mx ? (mx - mn) / mx : 0; };
const toRgb = (c) => { const m = c.match(/^#([0-9a-f]{3}|[0-9a-f]{6})$/i); if (m) return hexRgb(c);
  const r = c.match(/^rgba?\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)(?:\s*,\s*([\d.]+))?\s*\)$/i); if (r && (r[4] === undefined || +r[4] >= .6)) return [+r[1], +r[2], +r[3]]; return null; };
const css3 = ([r, g, b], a) => a === undefined ? `rgb(${r}, ${g}, ${b})` : `rgba(${r}, ${g}, ${b}, ${a})`;
// a pale tint pushed back to its hue, for a see-through version of it on a dark ground
const hue = (c) => c.map((v) => Math.max(0, Math.min(255, Math.round(255 - (255 - v) * 4))));
const lighten = (c, t) => c.map((v) => Math.round(v + (255 - v) * t));

function mapColor(prop, value) {
  const c = toRgb(value.trim()); if (!c) return null;
  const L = lum(c), S = sat(c);
  if (prop === 'color') {
    if (L < .3) return 'var(--text)';
    if (S < .25) return L < .45 ? 'var(--text)' : L < .8 ? 'var(--muted)' : null;
    return L < .55 ? css3(lighten(c, .55)) : null;
  }
  if (/border|outline/.test(prop)) return L > .7 ? (S < .25 ? 'var(--line)' : css3(hue(c), .55)) : null;
  // background
  if (L > .9 && S < .12) return 'var(--panel)';
  if (L > .78 && S < .2) return 'var(--panel2)';
  if (L > .72) return css3(hue(c), .2);
  return null;
}

const out = [];
const COLOR = /#[0-9a-f]{3,6}\b|rgba?\([^)]*\)/gi;
// walk the rules; @media blocks keep their condition
const walk = (text, wrap) => {
  const re = /([^{}]+)\{([^{}]*)\}|(@media[^{]+)\{((?:[^{}]*\{[^{}]*\})*[^{}]*)\}/g; let m;
  while ((m = re.exec(text))) {
    if (m[3]) { walk(m[4], m[3].trim()); continue; }
    const sel = m[1].replace(/\/\*[\s\S]*?\*\//g, '').trim(); if (!sel || sel.startsWith('@') || /data-style|data-theme|:root|^html,|^\*/.test(sel)) continue;
    const parts = sel.split(',').map((s) => s.trim()).filter((s) => s && !KEEP.test(s) && !/^html\b(?!\.)/.test(s) && s !== 'body');
    if (!parts.length) continue;
    const decls = [];
    for (const d of m[2].split(';')) {
      const i = d.indexOf(':'); if (i < 0) continue;
      const prop = d.slice(0, i).trim().toLowerCase(), val = d.slice(i + 1).trim();
      if (!/^(color|background|background-color|border|border-color|border-(top|bottom|left|right)|outline)$/.test(prop)) continue;
      if (/gradient|url\(|var\(/.test(val)) continue;
      const cols = val.match(COLOR); if (!cols || cols.length !== 1) continue;
      const to = mapColor(prop.startsWith('background') ? 'background' : prop, cols[0]); if (!to) continue;
      const p2 = prop === 'background' ? 'background-color' : prop;
      decls.push(`${p2}: ${p2 === 'background-color' || p2 === 'color' ? to : val.replace(cols[0], to)}`);
    }
    if (!decls.length) continue;
    // Same weight as the rule it answers (:where adds none), so it wins only by coming later: a more particular
    // rule (.pt-tab.on over .pt-tab) still wins, as it did on the white page.
    const sels = DARK.flatMap((s) => parts.map((p) => /^html\./.test(p) ? p.replace(/^html((\.[\w-]+)+)/, `html$1:where([data-style="${s}"])`) : `:where(html[data-style="${s}"]) ${p}`));
    const rule = `${[...new Set(sels)].join(', ')} { ${decls.join('; ')}; }`;
    out.push(wrap ? `${wrap} { ${rule} }` : rule);
  }
};
walk(css.replace(/\/\*[\s\S]*?\*\//g, ''), null);
const next = `${css}\n${START}\n${out.join('\n')}\n${END}\n`;
// --check (test/looks.test.js): fail when app.css changed and the section was not made again
if (process.argv.includes('--check')) {
  if (next !== fs.readFileSync(FILE, 'utf8')) { console.error('make-look-colors: app.css changed; run node tools/make-look-colors.mjs'); process.exit(1); }
  console.log('make-look-colors: up to date');
} else { fs.writeFileSync(FILE, next); console.log(`make-look-colors: ${out.length} rules written`); }
