// A tapped number's NEIGHBORS (the number screen's "With Its Neighbors", owner 2026-11-27): the other numbers it makes a
// combination with, and the combination card written for each pair. What counts as a combination is the owner's rule
// (.brain/numerology/combinations.md "What counts as a combination"): two numbers CLOSE TOGETHER (a center's main and
// sub vibration, a center and the aura beside it, an aura and the name beside it, a diamond's two parts, names next to
// each other, a psyche chart's mental strategies on its life expression diamond, the same spot in the two psyche
// charts) or two PRIMARY positions (day, life path, life expression, names). Never two far apart.
// `test/neighbors.test.js` holds this list and `diamondsOf` in server/insight.js to the same pairs.
//
// A card depends only on the two spots and the two numbers, never on the person: written once (by Claude sessions,
// tools/combo-cards), then shown on every chart with that pair. `knowledge/combo-cards.json` is GENERATED by
// `node tools/combo-cards/merge.mjs`; never hand-edited.
//
//   neighborsFor({ chart, position, n, at, inputs }) -> [{ kind, label, spot: { chart, position, n, sum }, key, card|null }]
//   cardKey(spotA, sumA, spotB, sumB) -> "name.heart=16|name.upperLeft=17" (the two sides sorted)
import fs from 'node:fs';
import { computeValues, normalizeInputs } from './positions.js';

const NUMEROSCOPES = ['name', 'vocation', 'personality', 'outer', 'inner'];
const RHOMBUS = new Set(NUMEROSCOPES);
// [spot a, spot b, kind]: a spot is "chart.position"; a side holding several numbers (middle names, sub vibrations)
// pairs each of them.
function pairList() {
  const out = [];
  const add = (a, b, kind) => out.push([a, b, kind]);
  for (const c of NUMEROSCOPES) {
    add(`${c}.heart`, `${c}.heartExtra`, 'circle');
    add(`${c}.solar`, `${c}.solarExtra`, 'circle');
    add(`${c}.heart`, `${c}.upperLeft`, 'center-aura'); add(`${c}.heart`, `${c}.upperRight`, 'center-aura');
    add(`${c}.solar`, `${c}.lowerLeft`, 'center-aura'); add(`${c}.solar`, `${c}.lowerRight`, 'center-aura');
    add(`${c}.upperLeft`, `${c}.upperRight`, 'diamond'); add(`${c}.lowerLeft`, `${c}.lowerRight`, 'diamond'); // mental and emotional diamond
    add('essence.day', `${c}.first`, 'diamond'); add('essence.day', `${c}.le`, 'diamond'); // public and spine diamond
    add(`${c}.first`, `${c}.last`, 'diamond'); // the line diamond, only when there is no middle name (see `line`)
  }
  for (const c of ['name', 'vocation', 'personality']) {
    add(`${c}.upperLeft`, `${c}.first`, 'aura-name'); add(`${c}.lowerLeft`, `${c}.first`, 'aura-name');
    add(`${c}.upperRight`, `${c}.last`, 'aura-name'); add(`${c}.lowerRight`, `${c}.last`, 'aura-name');
  }
  for (const [a, b] of [['day', 'month'], ['day', 'year'], ['month', 'year'], ['day', 'littleLp'], ['day', 'topAura'], ['outerAura', 'month']]) add(`essence.${a}`, `essence.${b}`, 'diamond');
  const primary = ['essence.day', 'essence.littleLp', 'name.le', 'name.first', 'name.middle', 'name.last'];
  for (let i = 0; i < primary.length; i++) for (let j = i + 1; j < primary.length; j++) add(primary[i], primary[j], 'primary');
  add('personality.le', 'vocation.le', 'heart-personality');
  for (const c of ['outer', 'inner']) add(`${c}.mindDiamond`, `${c}.leDiamond`, 'psyche-stack');
  // the two psyche charts side by side (the Psyche book's own method: the same spot in both, owner 2026-11-27)
  for (const p of ['heart', 'solar', 'mindDiamond', 'leDiamond', 'first', 'pillar']) add(`outer.${p}`, `inner.${p}`, 'psyche-twins');
  return out;
}
export const PAIRS = pairList();

export const cardKey = (spotA, sumA, spotB, sumB) => [`${spotA}=${Number(sumA)}`, `${spotB}=${Number(sumB)}`].sort().join('|');

let CARDS = null;
export function loadCards() {
  if (CARDS) return CARDS;
  try { CARDS = JSON.parse(fs.readFileSync(new URL('../knowledge/combo-cards.json', import.meta.url), 'utf8')).cards || {}; } catch { CARDS = {}; }
  return CARDS;
}
export const cardFor = (key) => loadCards()[key] || null;

// Every number of one chart, by spot: "name.middle" -> [{ n, sum }, ...].
function valuesBySpot(inputs) {
  const by = new Map();
  for (const v of computeValues(normalizeInputs(inputs || {}))) {
    const k = `${v.chart}.${v.position}`;
    if (!by.has(k)) by.set(k, []);
    by.get(k).push({ n: v.n, sum: v.sum });
  }
  return by;
}

export function neighborsFor({ chart, position, n = 0, at = 'name', inputs, sum = null } = {}) {
  const inp = normalizeInputs(inputs || {});
  if (!inp.name && !inp.day) return null;
  const by = valuesBySpot(inp);
  const spot = `${chart}.${position}`;
  const me = (by.get(spot) || []).find((x) => x.n === Number(n));
  if (!me || (sum !== null && me.sum !== Number(sum))) return null; // a stale drawing: the inputs do not hold the tapped number
  const host = RHOMBUS.has(at) ? at : 'name';
  const hasMiddle = (c) => (by.get(`${c}.middle`) || []).length > 0;
  const out = [], seen = new Set();
  const push = (kind, other, x) => {
    const id = `${other}#${x.n}`;
    if (seen.has(id) || (other === spot && x.n === me.n)) return;
    seen.add(id);
    const [oc, op] = other.split('.');
    const key = cardKey(spot, me.sum, other, x.sum);
    out.push({ kind, spot: { chart: oc, position: op, n: x.n, sum: x.sum }, key, card: cardFor(key) });
  };
  for (const [a, b, kind] of PAIRS) {
    if (a !== spot && b !== spot) continue;
    const other = a === spot ? b : a;
    const oc = other.split('.')[0];
    // the essence day sits on every numeroscope: only the one it was tapped on (and the essence) counts
    if (chart === 'essence' && position === 'day' && RHOMBUS.has(oc) && oc !== host) continue;
    // the line diamond (first beside last) exists only without a middle name
    if (kind === 'diamond' && /\.(first|last)$/.test(a) && /\.(first|last)$/.test(b) && a.split('.')[0] === b.split('.')[0] && hasMiddle(oc)) continue;
    for (const x of by.get(other) || []) push(kind, other, x);
  }
  // names next to each other on a line (first, middles, last), in every chart that has names
  if (['name', 'vocation', 'personality'].includes(chart) && ['first', 'middle', 'last'].includes(position)) {
    const line = [...(by.get(`${chart}.first`) || []).map((x) => ['first', x]), ...(by.get(`${chart}.middle`) || []).map((x) => ['middle', x]), ...(by.get(`${chart}.last`) || []).map((x) => ['last', x])];
    const i = line.findIndex(([p, x]) => p === position && x.n === me.n);
    for (const j of [i - 1, i + 1]) if (i >= 0 && line[j]) push('names', `${chart}.${line[j][0]}`, line[j][1]);
  }
  const ORDER = ['circle', 'center-aura', 'aura-name', 'names', 'diamond', 'psyche-stack', 'psyche-twins', 'heart-personality', 'primary'];
  return out.sort((x, y) => ORDER.indexOf(x.kind) - ORDER.indexOf(y.kind));
}
